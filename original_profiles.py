def _parse(text, fields):
    result = {}
    for line in text.strip().splitlines():
        parts = line.split('|')
        if len(parts) != fields:
            raise ValueError(f'Invalid profile: {parts[0]}')
        if parts[0] in result:
            raise ValueError(f'Duplicate profile: {parts[0]}')
        result[parts[0]] = parts[1:]
    return result

